"""Create four AHAB SRK keys in host SoftHSM and write a kas fragment"""

import argparse
import os
from pathlib import Path
import re
import secrets
import shutil
import subprocess


KEY_TYPES = {
    "secp256r1": "EC:prime256v1",
    "prime256v1": "EC:prime256v1",
    "secp384r1": "EC:secp384r1",
    "secp521r1": "EC:secp521r1",
    "rsa2048": "RSA:2048",
    "rsa3072": "RSA:3072",
    "rsa4096": "RSA:4096",
}


def run(command, env=None):
    result = subprocess.run(command, env=env, stdin=subprocess.DEVNULL,
                            stdout=subprocess.PIPE, stderr=subprocess.PIPE, text=True)
    if result.returncode:
        raise ValueError(f"{Path(command[0]).name} failed:\n{result.stderr.strip()}")
    return result.stdout.strip()


def host_module(override):
    if override:
        candidates = [override.expanduser()]
    else:
        candidates = [Path(directory) / "softhsm/libsofthsm2.so" for directory in
                      ("/usr/lib", "/usr/lib64", "/usr/local/lib")]
        candidates += sorted(Path("/usr/lib").glob("*/softhsm/libsofthsm2.so"))
        candidates += [Path("/usr/lib64/pkcs11/libsofthsm2.so")]
    for path in candidates:
        if path.is_file():
            return path.resolve()
    raise ValueError("Install SoftHSM on the host, or set --module to its libsofthsm2.so")


def output_path(value):
    path = Path(value)
    if path.exists() or path.is_symlink():
        raise ValueError(f"Output already exists: {path}. Choose a new path")
    path = path.resolve()
    if not re.fullmatch(r"[A-Za-z0-9_./+-]+", str(path)):
        raise ValueError("Output paths may contain only letters, digits, /, ., _, + or -")
    if not path.parent.is_dir():
        raise ValueError(f"Output parent directory does not exist: {path.parent}")
    return path


def fragment(root, label, srk_id):
    return f'''# Generated by tools/generate-softhsm-ahab-keys.py
header:
  version: 14

local_conf_header:
  softhsm_ahab_keys: |
    IMX_SIGN_ENABLE = "1"
    IMX_SIGN_CONFIG = ""
    IMX_SIGN_PQC_ENABLE = "0"
    IMX_SIGN_KEYDIR = "{root}/ahab"
    IMX_SIGN_SRK_FILES = "srk0.pub srk1.pub srk2.pub srk3.pub"
    IMX_SIGN_SRK_ID = "{srk_id}"
    IMX_SIGN_HASH_ALGORITHM = "default"
    IMX_SIGN_PKCS11_URI = "pkcs11:token={label};object=srk${{IMX_SIGN_SRK_ID}};type=private"
    IMX_SIGN_PKCS11_MODULE = "softhsm"
    IMX_SIGN_PKCS11_PIN_FILE = "{root}/pin"
    export SOFTHSM2_CONF = "{root}/softhsm2.conf"
'''


def generate(args):
    root = output_path(args.key_dir)
    kas = output_path(args.kas_fragment)
    if root == kas:
        raise ValueError("The key directory and kas fragment must have different paths")
    if not re.fullmatch(r"[A-Za-z0-9_-]{1,32}", args.token_label):
        raise ValueError("Token labels need 1 to 32 letters, digits, underscores or hyphens")

    module = host_module(args.module)
    pkcs11 = shutil.which("pkcs11-tool")
    openssl = shutil.which("openssl")
    if not pkcs11 or not openssl:
        raise ValueError("Install OpenSC (pkcs11-tool) and OpenSSL on the host")

    root.mkdir(mode=0o700)
    (root / "tokens").mkdir(mode=0o700)
    (root / "ahab").mkdir(mode=0o700)
    pin, so_pin = secrets.token_hex(16), secrets.token_hex(16)
    (root / "pin").write_text(pin + "\n")
    (root / "so-pin").write_text(so_pin + "\n")
    config = root / "softhsm2.conf"
    config.write_text(f"directories.tokendir = {root}/tokens\nobjectstore.backend = file\n")
    env = os.environ.copy()
    env.update(SOFTHSM2_CONF=str(config), AHAB_USER_PIN=pin, AHAB_SO_PIN=so_pin)
    command = [str(pkcs11), "--module", str(module)]
    run(command + ["--slot-index", "0", "--init-token", "--label", args.token_label,
                   "--so-pin", "env:AHAB_SO_PIN"], env)
    command += ["--token-label", args.token_label]
    run(command + ["--login", "--login-type", "so", "--so-pin", "env:AHAB_SO_PIN",
                   "--init-pin", "--pin", "env:AHAB_USER_PIN"], env)
    env.pop("AHAB_SO_PIN")
    command += ["--login", "--pin", "env:AHAB_USER_PIN"]
    for index in range(4):
        label, key_id = f"srk{index}", f"{index + 1:02x}"
        print(f"Generating AHAB {label} ({args.ahab_type})", flush=True)
        run(command + ["--keypairgen", "--key-type", KEY_TYPES[args.ahab_type],
                       "--id", key_id, "--label", label, "--usage-sign", "--sensitive"], env)
        der = root / "ahab" / f"{label}.der"
        public = root / "ahab" / f"{label}.pub"
        run(command + ["--read-object", "--type", "pubkey", "--id", key_id,
                       "--output-file", str(der)], env)
        run([str(openssl), "pkey", "-pubin", "-inform", "DER", "-in", str(der),
             "-out", str(public)])
        der.unlink()
    # Publish the fragment only after all four keys have been generated
    with kas.open("x") as output:
        output.write(fragment(root, args.token_label, args.srk_id))
    print(f"AHAB public keys: {root}/ahab")
    print(f"Token store and PIN files: {root}")
    print(f"Kas fragment: {kas}")
    print(f"From the layer directory: kas build kas-imx-secure.yml:kas-signing-keys.yml:{kas}")


def main():
    parser = argparse.ArgumentParser(description=__doc__, epilog=(
        "Requires host SoftHSM, OpenSC (pkcs11-tool) and OpenSSL. "
        "Creates a new token with random user and SO PIN files. Existing output paths are never replaced."))
    parser.add_argument("--key-dir", default="imx-softhsm-ahab")
    parser.add_argument("--kas-fragment", default="kas-softhsm-ahab.yml")
    parser.add_argument("--ahab-type", choices=KEY_TYPES, default="secp384r1")
    parser.add_argument("--token-label", default="ahab-signing")
    parser.add_argument("--srk-id", type=int, choices=range(4), default=0)
    parser.add_argument("--module", type=Path,
                        help="Host libsofthsm2.so path (default: detect the installed library)")
    args = parser.parse_args()
    os.umask(0o077)
    try:
        generate(args)
    except (OSError, ValueError) as error:
        parser.exit(1, f"Error: {error}\n")


if __name__ == "__main__":
    main()
